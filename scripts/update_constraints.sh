#!/usr/bin/env bash
# Regenerate server/constraints.txt: the exact versions of everything the server ships with.
#
#   ./scripts/update_constraints.sh && ./scripts/check.sh
#
# The server's own dependencies are lower bounds (pyproject.toml), so an install made
# without this file takes whatever was released that morning. In November 2026 that was
# FastAPI 0.162, which the server did not start on (iteration 100). Every install that
# ships or is tested — the Docker image, the desktop installers, CI — uses this file, so
# what is released is what was tested, and an upgrade is a commit somebody reviewed.
#
# Run it to take newer versions on purpose, then run the full check before committing.
# The `datumaro` extra is left out: it is optional, heavy, and tested against whatever
# Datumaro currently is (`.github/workflows/datumaro.yml`).
set -euo pipefail
cd "$(dirname "$0")/.."

venv="$(mktemp -d)/venv"
python3 -m venv "$venv"
"$venv/bin/pip" install --quiet --upgrade pip
"$venv/bin/pip" install --quiet "./server[postgres,s3,media,worker,redis,oidc,saml,tracing,desktop,dev]"
{
  echo "# Generated by scripts/update_constraints.sh — do not edit by hand."
  echo "# Exact versions for every install that ships or is tested; see that script for why."
  "$venv/bin/pip" freeze --exclude-editable | grep -v -i '^curvevision'
} > server/constraints.txt
rm -rf "$(dirname "$venv")"
echo "wrote server/constraints.txt ($(grep -vc '^#' server/constraints.txt) packages)"
